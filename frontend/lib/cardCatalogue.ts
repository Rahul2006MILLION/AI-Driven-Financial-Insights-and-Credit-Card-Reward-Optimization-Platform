export interface CatalogueRule {
  category_id: string;
  merchant_pattern?: string;
  reward_type: "CASHBACK" | "REWARD_POINTS" | "MILES";
  reward_rate_percentage: number;
  point_monetary_value?: number;
  min_transaction_amount?: number;
  monthly_cap_amount?: number | null;
  is_excluded?: boolean;
  exclusion_reason?: string;
}

export interface CatalogueBenefit {
  benefit_type: string;
  title: string;
  description: string;
  applicable_category: string;
  reward_basis: string;
  reward_percentage_or_points?: number;
  annual_value_estimate: number;
}

export interface CatalogueCard {
  id: string;
  bankId: string;
  bankName: string;
  cardName: string;
  cardVariant: string;
  defaultNetwork: "VISA" | "MASTERCARD" | "AMEX" | "RUPAY" | "DINERS";
  joiningFee: number;
  annualFee: number;
  renewalWaiverSpend?: number;
  feeWaiverConditionDetails?: string;
  billingCycleDay: number;
  termsSourceUrl: string;
  lastVerifiedDate?: string;
  highlightTag: string;
  badgeType: "VERIFIED_CATALOGUE" | "MANUAL_CUSTOM";
  rules: CatalogueRule[];
  benefits: CatalogueBenefit[];
}

