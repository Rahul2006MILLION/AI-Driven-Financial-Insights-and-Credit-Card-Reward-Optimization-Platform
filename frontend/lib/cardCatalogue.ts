export const getThemeForBank = (bankNameOrId: string) => {
  const normalized = bankNameOrId.toLowerCase();
  const issuer = BANK_ISSUERS.find(
    (b) =>
      b.id === normalized ||
      b.name.toLowerCase().includes(normalized) ||
      normalized.includes(b.shortName.toLowerCase()) ||
      normalized.includes(b.id)
  );
  return issuer?.theme || BANK_ISSUERS.find((b) => b.id === "custom")!.theme;
};

