# 4. RECONCILED TASK & CONSENT ALIASES
# ------------------------------------------------------------------------------

def test_reconciled_task_and_consent_aliases():
    """
    Verifies that:
    1. Both CARD_RECOMMENDATION and CARD_RECOMMENDATION_EXPLANATION are valid.
    2. Both SPENDING_SUMMARY and SPENDING_ANALYSIS_SUMMARY are valid.
    3. Both allow_spending_context and allow_spending_summary_context map properly in schemas.
    """
    # 1. Task enum aliases
    assert AiTaskType.CARD_RECOMMENDATION == "CARD_RECOMMENDATION"
    assert AiTaskType.CARD_RECOMMENDATION_EXPLANATION == "CARD_RECOMMENDATION_EXPLANATION"
    assert AiTaskType.SPENDING_SUMMARY == "SPENDING_SUMMARY"
    assert AiTaskType.SPENDING_ANALYSIS_SUMMARY == "SPENDING_ANALYSIS_SUMMARY"

    # Context builder works with both aliases
    ctx1, class1 = PrivacyContextBuilder.build_minimized_context(
        task_type=AiTaskType.CARD_RECOMMENDATION,
        allow_card_context=False
    )
    ctx2, class2 = PrivacyContextBuilder.build_minimized_context(
        task_type=AiTaskType.CARD_RECOMMENDATION_EXPLANATION,
        allow_card_context=False
    )
    assert ctx1 == ctx2
    assert class1 == class2 == DataClassification.SENSITIVE

    # 2. Schema alias reconciliation
    req1 = AiConsentUpdateRequest(
        external_ai_enabled=True,
        allow_spending_summary_context=True
    )
    assert req1.allow_spending_context is True
    assert req1.allow_spending_summary_context is True

    req2 = AiConsentUpdateRequest(
        external_ai_enabled=True,
        allow_spending_context=False
    )
    assert req2.allow_spending_context is False
    assert req2.allow_spending_summary_context is False
