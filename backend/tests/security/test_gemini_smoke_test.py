# 2. DEPRECATED MODEL REJECTION VERIFICATION
# ------------------------------------------------------------------------------

@pytest.mark.asyncio
async def test_deprecated_model_rejection_prevents_silent_fallback():
    """
    Verifies that if an environment variable or configuration attempts to use
    a deprecated model (e.g. gemini-1.5-flash, retired Sept 29, 2025),
    PrivacyGateway refuses to execute it and returns an explicit DEPRECATED_MODEL_REJECTED error.
    """
    async with AsyncSessionLocal() as session:
        user_id = str(uuid.uuid4())
        profile = Profile(
            id=user_id,
            email=f"depr_{user_id[:8]}@example.com",
            full_name="Deprecated Model Tester",
            hashed_password=get_password_hash("Pass123!"),
            preferred_language="en",
            role="user"
        )
        session.add(profile)
        consent = UserAiConsent(
            user_id=user_id,
            external_ai_enabled=True,
            provider_preference="gemini"
        )
        session.add(consent)
        await session.commit()

        # Patch configuration to deprecated model
        with patch.object(settings, "AI_MODEL_NAME", "gemini-1.5-flash"), \
             patch.object(settings, "GEMINI_MODEL", None), \
             patch.object(settings, "GEMINI_API_KEY", "dummy_key"):
            result = await PrivacyGateway.execute_request(
                db=session,
                user_id=user_id,
                task_type=AiTaskType.GENERAL_QUERY,
                user_query="What is APR?",
                language="en"
            )

            assert result["success"] is False
            assert result["privacy_status"] == "DEPRECATED_MODEL_REJECTED"
            assert "retired by Google" in result["response"]
            assert result["is_external_ai_used"] is False


