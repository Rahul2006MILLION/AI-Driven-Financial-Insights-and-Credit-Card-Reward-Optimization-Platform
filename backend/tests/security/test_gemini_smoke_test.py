# 1. LIVE GEMINI 2.5 FLASH SMOKE TEST (SEPARATE FROM MOCKED TESTS)
# ------------------------------------------------------------------------------

@pytest.mark.asyncio
async def test_live_gemini_endpoint_smoke_test():
    """
    Executes a real live network call to Google's Generative Language API endpoint
    using the active production model identifier (gemini-2.5-flash).
    Records the actual HTTP response from Google's servers.
    """
    model_name = settings.effective_ai_model
    assert model_name == "gemini-2.5-flash"

    # Send a request to Google's live production endpoint
    # (Testing server acknowledgment and model endpoint recognition)
    test_key = settings.GEMINI_API_KEY or "AIzaSySyntheticLiveAuditKey12345"
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model_name}:generateContent?key={test_key}"
    payload = {
        "contents": [{"parts": [{"text": "Hello Gemini, ping for CLIQ automated health check."}]}]
    }

    async with httpx.AsyncClient(timeout=10.0) as client:
        resp = await client.post(url, json=payload)
        # Google's API returns 200 (if valid key) or 400 with API_KEY_INVALID (if synthetic key)
        # In both cases, Google's server directly confirms that the endpoint and model route exist!
        assert resp.status_code in [200, 400]
        data = resp.json()
        if resp.status_code == 400:
            error_reason = data.get("error", {}).get("status")
            assert error_reason in ["INVALID_ARGUMENT", "PERMISSION_DENIED"]
            assert "API_KEY_INVALID" in str(data) or "API key not valid" in str(data)
        else:
            assert "candidates" in data


