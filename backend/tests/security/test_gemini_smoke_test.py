# 3. ERROR HANDLING & PROVIDER UNAVAILABILITY RESILIENCE
# ------------------------------------------------------------------------------

@pytest.mark.asyncio
async def test_provider_unavailable_graceful_local_fallback():
    """
    Verifies that when the external AI provider is unavailable (HTTP 503, timeout, or DNS error),
    PrivacyGateway catches the exception, logs LOCAL_FALLBACK in the audit log,
    and returns a valid response generated by the local grounded engine.
    """
    async with AsyncSessionLocal() as session:
        user_id = str(uuid.uuid4())
        profile = Profile(
            id=user_id,
            email=f"unavail_{user_id[:8]}@example.com",
            full_name="Unavailability Tester",
            hashed_password=get_password_hash("Pass123!"),
            preferred_language="en",
            role="user"
        )
        session.add(profile)
        consent = UserAiConsent(
            user_id=user_id,
            external_ai_enabled=True,
            provider_preference="gemini"
        )
        session.add(consent)
        await session.commit()

        # Mock an HTTP connection failure
        async def mock_network_error(*args, **kwargs):
            raise httpx.ConnectError("Connection refused by external provider")

        with patch.object(settings, "GEMINI_API_KEY", "test_key"), \
             patch.object(httpx.AsyncClient, "post", mock_network_error):
            result = await PrivacyGateway.execute_request(
                db=session,
                user_id=user_id,
                task_type=AiTaskType.FINANCIAL_EDUCATION,
                user_query="What is a credit card billing cycle?",
                language="en"
            )

            # System must NOT crash; must return grounded local response
            assert result["success"] is True
            assert result["is_external_ai_used"] is False
            assert result["provider_used"] == "local_grounded_engine"
            assert result["privacy_status"] == "LOCAL_PROCESSING_PROTECTED"
            assert len(result["response"]) > 0


